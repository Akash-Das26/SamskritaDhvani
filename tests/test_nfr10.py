def test_synthetic_fixture_sheet_is_refused_without_fixtures_flag(
    tmp_path, capsys
):
    """The non-shipped-data guard: a fixture sheet cannot be mistaken
    for real ratings, so it cannot yield a number by accident."""
    ids = _attempts(30)
    ratings = _steps(ids)
    sheet_a = _write_sheet(tmp_path, "rater_a.md", ratings, rater_id="fixture-A")
    sheet_b = _write_sheet(tmp_path, "rater_b.md", ratings, rater_id="fixture-B")
    scores = _write_scores(tmp_path, {a: 50.0 for a in ids})
    rc = main(["--ratings", str(sheet_a), str(sheet_b),
               "--scores", str(scores)])
    _refusal(capsys, rc, "SYNTHETIC-FIXTURE")


def test_shipped_blank_template_is_refused(tmp_path, capsys):
    """Pointing the CLI at the tracked template must not produce a number."""
    scores = _write_scores(tmp_path, {a: 50.0 for a in _attempts(30)})
    template = Path("files/Nfr10RatingSheet.md")
