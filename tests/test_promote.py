def _speech_wav(path: Path, *, seconds: float = 1.0, f0: float = 130.0,
                scale: float = 0.35) -> Path:
    """Synthetic voiced harmonic stack (NFR-02), VAD-detectable."""
    sr = 16_000
    t = np.arange(int(sr * seconds)) / sr
    y = np.zeros_like(t)
    for k in (1, 2, 3, 4, 5):
        y += np.sin(2 * np.pi * f0 * k * t) / k
    env = 0.5 * (1 - np.cos(np.pi * np.minimum(1.0, t / seconds)))
    pcm = (np.clip(scale * y * env, -1.0, 1.0) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(pcm.tobytes())
    return path


def _silence_wav(path: Path, seconds: float = 1.0) -> Path:
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(16_000)
        w.writeframes(np.zeros(int(16_000 * seconds), dtype="<i2").tobytes())
    return path


def _check_row(file: str, **overrides) -> str:
    values = {
        "File": file,
        "Session ID": SESSION,
        "Item": "kRSNa",
        "Take #": "0",
        "Duration (s)": "1.00",
        "Peak dBFS": "-9.0",
        "Clipping?": "no",
        "Silence trimmed?": "no",
        "Transcript verified?": "yes",
        "Sweep date": "2026-10-23",
        "Provenance entry": "SPD-SYNTHETIC",
    }
    values.update(overrides)
    return "| " + " | ".join(values[f] for f in CHECK_FIELDS) + " |"


def _write_sheet(env, rows: list[str], *, values: dict | None = None,
                 session_cell: str | None = None) -> Path:
    fields = {
        "Session ID": session_cell if session_cell is not None else f"`{SESSION}`",
        "Date / time": "2026-01-01 10:00 IST (synthetic)",
        "Location / room": "synthetic fixture room",
        "Noise environment": "synthetic: none",
        "Reciter ID": "fixture-reciter (SYNTHETIC consent form)",
        "Reciter background": "synthetic fixture; none",
        "Recitation tradition": "synthetic fixture — not a real tradition",
        "Consent": "CONSENT-SYNTHETIC-01 (fixture form)",
        "Device": "synthetic fixture mic",
        "Recording format": "16 kHz mono PCM16 (synthetic)",
        "Levels": "peak -9 dBFS (synthetic)",
        "Materials & version": "27-word SPD list (synthetic fixture)",
        "Procedure": "synthetic fixture; no warm-up",
        "Post-session transfer": "none (synthetic fixture)",
    }
    fields.update(values or {})
    table = "\n".join(f"| **{k}** | {v} |" for k, v in fields.items())
    body = f"""# REC {SESSION} — synthetic fixture

**SYNTHETIC-FIXTURE** — generated by tests/test_promote.py.

## 1. Session sheet (one per recording session)

| Field | Value (fill in) |
|---|---|
{table}

## 2. Per-file checklist (one row per clip)

| File | Session ID | Item (word / ch.v) | Take # | Duration (s) | Peak dBFS | Clipping? | Silence trimmed? | Transcript verified? | Sweep date | Provenance entry |
|---|---|---|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}
"""
    path = env["prov_dir"] / f"REC_{SESSION}.md"
    path.write_text(body, encoding="utf-8")
    return path


