"""NFR-10 correlation tests — synthetic fixtures only (NFR-02).

Every rating sheet and every score record below is generated by the
helpers in this file and the sheet text carries the marker
``SYNTHETIC-FIXTURE``. No number produced here is evidence, is written
into ``files/Review.md``, or is presented as a measured correlation.
"""

import json
from pathlib import Path

import pytest
from scipy import stats

from samskrita_dhvani.nfr10 import main


# --------------------------------------------------------------- fixtures


def _sheet_text(
    ratings: dict[str, int],
    *,
    rater_id: str,
    role: str = "instructor",
    tradition: str = "synthetic fixture; no real tradition",
    not_rateable=(),
    marker: bool = True,
) -> str:
    rows = [
        f"| {attempt} | kRSNa | क | k | {value} | synthetic row |"
        for attempt, value in ratings.items()
    ]
    rows += [
        f"| {attempt} | kRSNa | क | k | N/A | synthetic row |"
        for attempt in not_rateable
    ]
    header = "# NFR-10 Rater Sheet — synthetic fixture\n"
    if marker:
        header += (
            "\n**SYNTHETIC-FIXTURE** — generated by tests/test_nfr10.py "
            "only (NFR-02). Not a human rating of any real attempt.\n"
        )
    return header + f"""
## Rater header (completed once per rater)

| Field | Value |
|---|---|
| Rater ID (name or pseudonym) | {rater_id} |
| Role | {role} |
| Native language(s) | none (synthetic fixture) |
| Script familiarity (Devanagari / IAST / neither) | IAST |
| Recitation tradition practiced or studied | {tradition} |
| Years of Sanskrit study / teaching | 0 (synthetic fixture) |
| Date of rating | 2026-01-01 |

## Rubric (fixed — applies to every item)

| Rating | Meaning |
|---|---|
| 1 | synthetic |
| 5 | synthetic |

## Ratings (one row per attempt — synthetic)

| Attempt ID | Word ID | Devanagari | IAST | Rating (1–5) | Notes (optional) |
|---|---|---|---|---|---|
""" + "\n".join(rows) + """

## Rater footer

| Field | Value |
|---|---|
| Total attempts rated | synthetic |
"""


def _write_sheet(tmp_path: Path, name: str, ratings, **kw) -> Path:
    path = tmp_path / name
    path.write_text(_sheet_text(ratings, **kw), encoding="utf-8")
    return path


def _write_scores(tmp_path: Path, similarities: dict[str, float],
                  name: str = "scores.json") -> Path:
    path = tmp_path / name
    path.write_text(
        json.dumps({
            "scores": [
                {"attempt_id": attempt, "similarity_pct": value}
                for attempt, value in similarities.items()
            ]
        }),
        encoding="utf-8",
    )
    return path


def _attempts(n: int = 30) -> list[str]:
    return [f"a{i:02d}" for i in range(n)]


def _steps(ids: list[str]) -> dict[str, int]:
    """Ratings 1–5 in blocks — ties are deliberate and realistic."""
    return {a: 1 + (i * 5 // len(ids)) for i, a in enumerate(ids)}


# ---------------------------------------------------------- correlation


def test_synthetic_perfect_correlation_is_rho_one_with_n(tmp_path, capsys):
    ids = _attempts(30)
    ratings = _steps(ids)
    # Similarity is a strictly monotone function of the pooled rating:
    # constant within a tie group, so Spearman is exactly 1.
    sims = {a: float(ratings[a] * 10) for a in ids}
    sheet_a = _write_sheet(tmp_path, "rater_a.md", ratings, rater_id="fixture-A")
    sheet_b = _write_sheet(tmp_path, "rater_b.md", ratings, rater_id="fixture-B")
    scores = _write_scores(tmp_path, sims)
    out_json = tmp_path / "report.json"

    rc = main(["--ratings", str(sheet_a), str(sheet_b),
               "--scores", str(scores), "--json", str(out_json),
               "--fixtures"])
    assert rc == 0, capsys.readouterr().err
    report = json.loads(out_json.read_text(encoding="utf-8"))
    assert report["spearman_rho"] == pytest.approx(1.0)
    assert report["n"] == 30
    assert report["synthetic_fixture"] is True
    assert "SYNTHETIC FIXTURE" in capsys.readouterr().out


def test_synthetic_known_rho_matches_scipy_and_hand_value(tmp_path, capsys):
    """Five tie-free attempts with a hand-known rho = 0.9."""
    ids = [f"a{i}" for i in range(5)]
    ratings = {a: i + 1 for i, a in enumerate(ids)}
    sims = {"a0": 10.0, "a1": 20.0, "a2": 30.0, "a3": 50.0, "a4": 40.0}
    sheet_a = _write_sheet(tmp_path, "rater_a.md", ratings, rater_id="fixture-A")
    sheet_b = _write_sheet(tmp_path, "rater_b.md", ratings, rater_id="fixture-B")
    scores = _write_scores(tmp_path, sims)
    out_json = tmp_path / "report.json"

    rc = main(["--ratings", str(sheet_a), str(sheet_b),
               "--scores", str(scores), "--json", str(out_json),
               "--min-n", "5", "--fixtures"])
    assert rc == 0, capsys.readouterr().err
    report = json.loads(out_json.read_text(encoding="utf-8"))
    assert report["spearman_rho"] == pytest.approx(0.9)
    assert report["n"] == 5
    expected = stats.spearmanr(
        [sims[a] for a in ids], [ratings[a] for a in ids]
    )
    assert report["spearman_rho"] == pytest.approx(float(expected.statistic))
    assert report["p_value"] == pytest.approx(float(expected.pvalue))


def test_synthetic_ties_use_average_ranks_like_scipy(tmp_path, capsys):
    ids = _attempts(30)
    ratings_a = _steps(ids)
    # Second rater mostly agrees, with three deliberate one-point
    # differences — enough to vary the pooled mean (and the agreement).
    ratings_b = dict(ratings_a)
    for attempt, bump in ((ids[5], 1), (ids[17], 1), (ids[23], 1)):
        ratings_b[attempt] = min(5, ratings_b[attempt] + bump)
    sims = {a: float(ratings_a[a] * 7 + (i % 3)) for i, a in enumerate(ids)}
    sheet_a = _write_sheet(tmp_path, "rater_a.md", ratings_a, rater_id="fixture-A")
    sheet_b = _write_sheet(tmp_path, "rater_b.md", ratings_b, rater_id="fixture-B")
    scores = _write_scores(tmp_path, sims)
    out_json = tmp_path / "report.json"

    rc = main(["--ratings", str(sheet_a), str(sheet_b),
               "--scores", str(scores), "--json", str(out_json),
               "--fixtures"])
    assert rc == 0, capsys.readouterr().err
    report = json.loads(out_json.read_text(encoding="utf-8"))

    pooled = [(ratings_a[a] + ratings_b[a]) / 2 for a in ids]
    expected = stats.spearmanr([sims[a] for a in ids], pooled)
    assert report["spearman_rho"] == pytest.approx(float(expected.statistic))
    assert report["n"] == 30
    # The near-agreeing raters must show strong positive agreement.
    assert report["agreement"][0]["rho"] > 0.9


def test_synthetic_two_rater_agreement_precedes_machine_correlation(
    tmp_path, capsys
):
    ids = _attempts(30)
    ratings_a = _steps(ids)
    ratings_b = {a: min(5, v + 1) for a, v in ratings_a.items()}
    sims = {a: float(ratings_a[a] * 10) for a in ids}
    sheet_a = _write_sheet(tmp_path, "rater_a.md", ratings_a, rater_id="fixture-A")
    sheet_b = _write_sheet(tmp_path, "rater_b.md", ratings_b, rater_id="fixture-B")
    scores = _write_scores(tmp_path, sims)
    out_json = tmp_path / "report.json"

    rc = main(["--ratings", str(sheet_a), str(sheet_b),
               "--scores", str(scores), "--json", str(out_json),
               "--fixtures"])
    assert rc == 0, capsys.readouterr().err
    report = json.loads(out_json.read_text(encoding="utf-8"))
    assert len(report["agreement"]) == 1
    pair = report["agreement"][0]
    assert pair["n"] == 30
    expected = stats.spearmanr(
        [ratings_a[a] for a in ids], [ratings_b[a] for a in ids]
    )
    assert pair["rho"] == pytest.approx(float(expected.statistic))

    printed = capsys.readouterr().out
    assert printed.index("inter-rater agreement") < printed.index(
        "score vs rating"
    )
    # The rater's header metadata is reported, not just the number.
    assert "role: instructor" in printed
    assert "background: native language(s) none (synthetic fixture)" in printed
    assert "tradition: synthetic fixture; no real tradition" in printed


