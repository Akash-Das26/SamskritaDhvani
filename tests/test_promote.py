def test_synthetic_mixed_session_promotes_only_passing_clips(env, capsys):
    def good(d):
        _speech_wav(d / "spd_kRSNa_canonical_t0.wav")

    def silent(d):
        _silence_wav(d / "spd_kRSNa_recitation_t0.wav")

    def second_good(d):
        _speech_wav(d / "spd_yoga_recitation_t0.wav", f0=160.0)

    def unlisted(d):
        _speech_wav(d / "spd_dharma_recitation_t0.wav", f0=120.0)

    d = _session(env, clips=(good, silent, second_good, unlisted))
    _write_sheet(env, [
        _check_row("spd_kRSNa_canonical_t0.wav"),
        _check_row("spd_kRSNa_recitation_t0.wav"),
        _check_row("spd_yoga_recitation_t0.wav"),
        # spd_dharma_recitation_t0.wav deliberately has no row
    ])
    rc = pr.main(["--session", SESSION, "--apply"])
    out = capsys.readouterr().out
    assert rc == 0
    assert "promoted 2 clip(s); held 2" in out
    assert (d / "spd_kRSNa_canonical_t0.wav").exists() is False
    assert (d / "spd_yoga_recitation_t0.wav").exists() is False
    assert (d / "spd_kRSNa_recitation_t0.wav").is_file()
    assert (d / "spd_dharma_recitation_t0.wav").is_file()
    assert "held by reason: checklist_row 1 · sweep 1" in out


