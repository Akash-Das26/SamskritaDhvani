# ------------------------------------------------------------ refusals


def _refusal(capsys, rc: int, needle: str) -> str:
    assert rc == 2
    err = capsys.readouterr().err.strip()
    assert err.endswith("no ratings, no number")
    assert "\n" not in err  # one loud line
    assert needle in err
    return err


def test_synthetic_fixture_missing_ratings_file_is_refused(
    tmp_path, capsys
):
    ids = _attempts(30)
    scores = _write_scores(tmp_path, {a: 50.0 for a in ids})
    rc = main(["--ratings", str(tmp_path / "absent.md"),
               "--scores", str(scores), "--fixtures"])
    _refusal(capsys, rc, "ratings file not found")


