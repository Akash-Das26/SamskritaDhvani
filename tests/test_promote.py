def test_synthetic_all_gates_pass_and_apply_moves_clips(env, capsys):
    _session(env, clips=(_canonical, _recitation))
    _write_sheet(env, [
        _check_row("spd_kRSNa_canonical_t0.wav"),
        _check_row("spd_kRSNa_recitation_t0.wav"),
    ])

    rc = pr.main(["--session", SESSION, "--apply"])
    out = capsys.readouterr().out
    assert rc == 0, out
    assert (env["spd"] / "reference_words" / "kRSNa.wav").is_file()
    assert (env["spd"] / "recitations" / "kRSNa__t0.wav").is_file()
    assert not (env["incoming"] / SESSION / "spd_kRSNa_canonical_t0.wav").exists()
    assert "promoted 2 clip(s); held 0" in out


